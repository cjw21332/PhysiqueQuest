import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
const source = path => readFile(new URL(`../${path}`, import.meta.url), 'utf8');
test('password recovery uses server-issued 6-digit codes and shows provider setup state', async () => {
  const screen = await source('sections/Forgot Password/ForgotPasswordFlow.tsx');
  const api = await source('lib/api.ts');
  assert.match(screen, /requestPasswordReset/);
  assert.match(screen, /verifyPasswordResetCode\(requestId, code\)/);
  assert.match(screen, /confirmPasswordReset\(passwordData\)/);
  assert.match(screen, /setRequestId\(response\.requestId\)/);
  assert.match(screen, /setResetToken\(result\.resetToken\)/);
  assert.match(screen, /confirmPasswordReset/);
  assert.match(screen, /6-digit code/);
  assert.match(screen, /response\.code/);
  assert.match(screen, /Verification email is unavailable/);
  assert.match(screen, /requestPasswordChange/);
  assert.match(screen, /verifyPasswordChange\(requestId, code\)/);
  assert.match(screen, /confirmPasswordChange\(passwordData\)/);
  assert.match(api, /password-change\/request/);
  assert.match(api, /password-change\/verify/);
  assert.match(api, /password-change\/confirm/);
  assert.match(api, /JSON\.stringify\(\{ requestId, code \}\)/);
  assert.match(api, /JSON\.stringify\(data\)/);
  assert.doesNotMatch(screen, /Simulate OTP|Show success modal/);
  assert.match(api, /password-reset\/request/);
  assert.match(api, /password-reset\/verify/);
  assert.match(api, /password-reset\/confirm/);
});
