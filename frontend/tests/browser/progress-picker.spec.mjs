  upper.dayIndex = 3;
  upper.scheduledDate = '2026-11-12';
  upper.exercises = [{ exerciseId: 'upper-curl', name: 'Upper Curl', equipment: 'Dumbbells', sets: 1 }];
  workouts.push(upper);
  const standalone = workout('5', '2026-11-15T12:00:00Z', 'standalone-lift', 8, 15);
  standalone.exercises = [{ exerciseId: 'standalone-lift', name: 'Standalone Lift', equipment: 'Dumbbells', sets: 1 }];
