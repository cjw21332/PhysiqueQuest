import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';

const source = path => readFile(new URL(`../${path}`, import.meta.url), 'utf8');

test('coach plan is generated by the backend and rendered from its response', async () => {
  const plan = await source('sections/Coach/CoachPlan.tsx');
  assert.match(plan, /useCoachPlan/);
  assert.match(plan, /plan\.days/);
  assert.match(plan, /plan\.libraryReady/);
  assert.match(plan, /Start session/);
  assert.doesNotMatch(plan, /const workoutTitles =/);
  assert.doesNotMatch(plan, /const todayExercises = \[/);
});

test('the API client exposes the coach plan and leaderboard endpoints', async () => {
  const client = await source('lib/api.ts');
  assert.match(client, /getCoachPlan\(\)/);
  assert.match(client, /getLeaderboard\(period/);
  assert.match(client, /CoachPlanRecord/);
  assert.match(client, /LeaderboardRecord/);
});
